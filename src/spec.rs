/// Vrai si `mc` est `base` ou l'un de ses sous-types — l'équivalent du
/// `instanceof` sur lequel reposent les règles du validateur de référence.
pub fn is_kind_of(mc: &str, base: &str) -> bool {
    mc == base || supertypes(mc).contains(&base)
}

/// Vrai si `mc` est (un sous-type de) l'une des `bases`.
pub fn is_any_kind_of(mc: &str, bases: &[&str]) -> bool {
    bases.iter().any(|b| is_kind_of(mc, b))
}

/// Super-classes transitives de `mc` ; vide si la métaclasse est inconnue.
pub fn supertypes(mc: &str) -> &'static [&'static str] {
    SUPERTYPES
        .binary_search_by(|(n, _)| (*n).cmp(mc))
        .map(|i| SUPERTYPES[i].1)
        .unwrap_or(&[])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted() {
        assert!(SUPERTYPES.windows(2).all(|w| w[0].0 < w[1].0));
    }

    #[test]
    fn instanceof_follows_the_metamodel() {
        // Les quatre cas que les anciennes heuristiques de sous-chaînes
        // manquaient ou inventaient.
        assert!(is_kind_of("ConcernDefinition", "RequirementDefinition"));
        assert!(is_kind_of("ViewpointDefinition", "RequirementDefinition"));
        assert!(is_kind_of("SatisfyRequirementUsage", "RequirementUsage"));
        assert!(is_kind_of("VerificationCaseDefinition", "CaseDefinition"));
        assert!(is_kind_of("IncludeUseCaseUsage", "CaseUsage"));
    }

    #[test]
    fn unrelated_types_are_not_confused() {
        assert!(!is_kind_of("PartDefinition", "RequirementDefinition"));
        assert!(!is_kind_of("RequirementUsage", "CaseUsage"));
        assert!(!is_kind_of("ActionDefinition", "CaseDefinition"));
        assert!(supertypes("PasUneMétaclasse").is_empty());
    }

    #[test]
    fn a_type_is_an_instance_of_itself() {
        assert!(is_kind_of("CaseUsage", "CaseUsage"));
        assert!(is_any_kind_of(
            "ConcernUsage",
            &["CaseUsage", "RequirementUsage"]
        ));
        assert!(!is_any_kind_of(
            "PartUsage",
            &["CaseUsage", "RequirementUsage"]
        ));
    }
}
